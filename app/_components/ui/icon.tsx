export type IconName = keyof typeof ICONS;

type AppIconProps = Omit<SVGProps<SVGSVGElement>, "ref"> & {
  name: IconName;
  size?: number;
};

export function AppIcon({ name, size = 18, className = "", strokeWidth = 2, ...props }: AppIconProps) {
  const Icon = ICONS[name];
  return <Icon aria-hidden="true" focusable="false" size={size} strokeWidth={Number(strokeWidth)} className={className} {...props} />;
}
